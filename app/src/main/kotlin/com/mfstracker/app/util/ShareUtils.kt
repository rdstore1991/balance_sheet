object ShareUtils {

    /**
     * Builds a neat monospace WhatsApp-friendly plain text summary of the balance sheet snapshot.
     */
    fun buildFormattedTextSummary(record: TrackerRecordEntity, currencyPrefix: String = "৳"): String {
        val sb = StringBuilder()
        sb.appendLine("━━━━━━━━━━━━━━━━━━━━━━━━━━━━")
        sb.appendLine("📊 *MFS TRACKER - BALANCE SHEET*")
        sb.appendLine("📅 *Date:* ${record.dateString}  🕒 *Time:* ${record.timeString}")
        sb.appendLine("━━━━━━━━━━━━━━━━━━━━━━━━━━━━")
        sb.appendLine()
        sb.appendLine("📌 *PART 1: MFS ACCOUNT BALANCES*")
        record.mfsBalances.forEach { item ->
            val formattedAcc = NumberFormatUtils.formatPhoneNumber(item.accountNumber)
            sb.appendLine("• ${item.provider.padEnd(12)} ($formattedAcc): $currencyPrefix ${item.balance.formatBdt()}")
        }
        sb.appendLine("👉 *TOTAL MFS:* $currencyPrefix ${record.totalMfsBalance.formatBdt()}")
        sb.appendLine()

        val nonZeroTxs = record.transactions.filter { it.amount > 0.0 || it.description.isNotBlank() }
        if (nonZeroTxs.isNotEmpty()) {
            sb.appendLine("📌 *PART 2: TRANSACTIONS LOG*")
            nonZeroTxs.forEach { tx ->
                val sign = if (tx.type == com.mfstracker.app.data.model.TransactionType.INCOME) "[+INC]" else "[-EXP]"
                val notesText = if (tx.notes.isNotBlank()) " (${tx.notes})" else ""
                sb.appendLine("• $sign ${tx.description}: $currencyPrefix ${tx.amount.formatBdt()}$notesText")
            }
            sb.appendLine("🔴 *Total Expenses:* $currencyPrefix ${record.totalDailyExpenses.formatBdt()}")
            sb.appendLine("🟢 *Total Income:* $currencyPrefix ${record.totalDailyIncome.formatBdt()}")
            sb.appendLine()
        }

        sb.appendLine("📌 *PART 3: RECONCILIATION SUMMARY*")
        sb.appendLine("💰 *Available Balance:* $currencyPrefix ${record.availableBalance.formatBdt()}")
        sb.appendLine("⏳ *Previous Balance:*  $currencyPrefix ${record.previousBalance.formatBdt()}")
        sb.appendLine("🎯 *Current MSA:*       $currencyPrefix ${record.msa.formatBdt()}")
        sb.appendLine("⏮️ *Previous MSA:*      $currencyPrefix ${record.previousMsa.formatBdt()}")
        sb.appendLine("━━━━━━━━━━━━━━━━━━━━━━━━━━━━")
        sb.appendLine("Generated by MFS Fund & Expense Tracker")

        return sb.toString()
    }

    /**
     * Renders a high-resolution, receipt-style digital summary card bitmap and saves it to cacheDir.
     * Returns the shareable content Uri via AndroidX FileProvider.
     */
    fun createReceiptCardBitmapUri(
        context: Context,
        record: TrackerRecordEntity,
        currencyPrefix: String = "৳"
    ): Uri {
        val width = 1080
        val baseHeight = 1600 + (record.transactions.size * 50)
        val bitmap = Bitmap.createBitmap(width, baseHeight, Bitmap.Config.ARGB_8888)
        val canvas = Canvas(bitmap)

        // Background
        val bgPaint = Paint().apply { color = android.graphics.Color.parseColor("#0F172A") }
        canvas.drawRect(0f, 0f, width.toFloat(), baseHeight.toFloat(), bgPaint)

        // Card Container
        val cardPaint = Paint().apply {
            color = android.graphics.Color.parseColor("#1E293B")
            isAntiAlias = true
        }
        val cardMargin = 40f
        canvas.drawRoundRect(
            cardMargin,
            cardMargin,
            width - cardMargin,
            baseHeight - cardMargin,
            32f,
            32f,
            cardPaint
        )

        // Paints
        val titlePaint = Paint().apply {
            color = android.graphics.Color.WHITE
            textSize = 54f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            isAntiAlias = true
        }

        val subtitlePaint = Paint().apply {
            color = android.graphics.Color.parseColor("#94A3B8")
            textSize = 34f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
            isAntiAlias = true
        }

        val sectionPaint = Paint().apply {
            color = android.graphics.Color.parseColor("#60A5FA")
            textSize = 38f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            isAntiAlias = true
        }

        val labelPaint = Paint().apply {
            color = android.graphics.Color.parseColor("#CBD5E1")
            textSize = 34f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.NORMAL)
            isAntiAlias = true
        }

        val valuePaint = Paint().apply {
            color = android.graphics.Color.WHITE
            textSize = 36f
            typeface = Typeface.create(Typeface.MONOSPACE, Typeface.BOLD)
            isAntiAlias = true
        }

        val primaryValuePaint = Paint().apply {
            color = android.graphics.Color.parseColor("#60A5FA")
            textSize = 42f
            typeface = Typeface.create(Typeface.MONOSPACE, Typeface.BOLD)
            isAntiAlias = true
        }

        val expensePaint = Paint().apply {
            color = android.graphics.Color.parseColor("#EF4444")
            textSize = 36f
            typeface = Typeface.create(Typeface.MONOSPACE, Typeface.BOLD)
            isAntiAlias = true
        }

        val incomePaint = Paint().apply {
            color = android.graphics.Color.parseColor("#10B981")
            textSize = 36f
            typeface = Typeface.create(Typeface.MONOSPACE, Typeface.BOLD)
            isAntiAlias = true
        }

        val linePaint = Paint().apply {
            color = android.graphics.Color.parseColor("#334155")
            strokeWidth = 3f
        }

        var y = 130f
        val leftX = 80f
        val rightX = width - 80f

        // Header
        canvas.drawText("MFS FUND & EXPENSE TRACKER", leftX, y, titlePaint)
        y += 55f
        canvas.drawText("Reconciliation Snapshot • ${record.dateString} ${record.timeString}", leftX, y, subtitlePaint)
        y += 40f
        canvas.drawLine(leftX, y, rightX, y, linePaint)
        y += 55f

        // PART 1
        canvas.drawText("PART 1: MFS ACCOUNT BALANCES", leftX, y, sectionPaint)
        y += 50f
        record.mfsBalances.forEach { item ->
            val accFormatted = NumberFormatUtils.formatPhoneNumber(item.accountNumber)
            val leftText = "${item.provider} ($accFormatted)"
            val rightText = "$currencyPrefix ${item.balance.formatBdt()}"
            canvas.drawText(leftText, leftX, y, labelPaint)
            val valWidth = valuePaint.measureText(rightText)
            canvas.drawText(rightText, rightX - valWidth, y, valuePaint)
            y += 48f
        }
        val totalMfsText = "$currencyPrefix ${record.totalMfsBalance.formatBdt()}"
        canvas.drawText("TOTAL MFS BALANCES", leftX, y, primaryValuePaint)
        val totalWidth = primaryValuePaint.measureText(totalMfsText)
        canvas.drawText(totalMfsText, rightX - totalWidth, y, primaryValuePaint)

        y += 40f
        canvas.drawLine(leftX, y, rightX, y, linePaint)
        y += 55f

        // PART 2 (Expenses & Income)
        canvas.drawText("PART 2: DAILY SUMMARY", leftX, y, sectionPaint)
        y += 50f
        val expVal = "$currencyPrefix ${record.totalDailyExpenses.formatBdt()}"
        canvas.drawText("Total Daily Expenses", leftX, y, labelPaint)
        canvas.drawText(expVal, rightX - expensePaint.measureText(expVal), y, expensePaint)
        y += 48f

        val incVal = "$currencyPrefix ${record.totalDailyIncome.formatBdt()}"
        canvas.drawText("Total Daily Income", leftX, y, labelPaint)
        canvas.drawText(incVal, rightX - incomePaint.measureText(incVal), y, incomePaint)

        y += 40f
        canvas.drawLine(leftX, y, rightX, y, linePaint)
        y += 55f

        // PART 3 (Reconciliation)
        canvas.drawText("PART 3: RECONCILIATION & MSA", leftX, y, sectionPaint)
        y += 55f

        val availVal = "$currencyPrefix ${record.availableBalance.formatBdt()}"
        canvas.drawText("Available Balance (Auto-Mirrored)", leftX, y, labelPaint)
        canvas.drawText(availVal, rightX - primaryValuePaint.measureText(availVal), y, primaryValuePaint)
        y += 50f

        val prevBalVal = "$currencyPrefix ${record.previousBalance.formatBdt()}"
        canvas.drawText("Previous Balance", leftX, y, labelPaint)
        canvas.drawText(prevBalVal, rightX - valuePaint.measureText(prevBalVal), y, valuePaint)
        y += 50f

        val msaVal = "$currencyPrefix ${record.msa.formatBdt()}"
        canvas.drawText("Current MSA", leftX, y, labelPaint)
        canvas.drawText(msaVal, rightX - valuePaint.measureText(msaVal), y, valuePaint)
        y += 50f

        val prevMsaVal = "$currencyPrefix ${record.previousMsa.formatBdt()}"
        canvas.drawText("Previous MSA", leftX, y, labelPaint)
        canvas.drawText(prevMsaVal, rightX - valuePaint.measureText(prevMsaVal), y, valuePaint)

        // Save to file
        val imagesFolder = File(context.cacheDir, "shared_receipts")
        imagesFolder.mkdirs()
        val file = File(imagesFolder, "receipt_${record.id}_${System.currentTimeMillis()}.png")
        FileOutputStream(file).use { out ->
            bitmap.compress(Bitmap.CompressFormat.PNG, 100, out)
            out.flush()
        }

        return FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            file
        )
    }

    fun shareText(context: Context, text: String, title: String = "Share Balance Sheet Summary") {
        val sendIntent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_TEXT, text)
        }
        val chooser = Intent.createChooser(sendIntent, title)
        context.startActivity(chooser)
    }

    fun shareImage(context: Context, uri: Uri, caption: String? = null, title: String = "Share Receipt Card") {
        val sendIntent = Intent(Intent.ACTION_SEND).apply {
            type = "image/png"
            putExtra(Intent.EXTRA_STREAM, uri)
            if (!caption.isNullOrBlank()) {
                putExtra(Intent.EXTRA_TEXT, caption)
            }
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        val chooser = Intent.createChooser(sendIntent, title).apply {
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        context.startActivity(chooser)
    }
}

